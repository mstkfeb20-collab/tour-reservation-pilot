-- 返金待ち。予約を取り消したとき、入金額が取消料より多ければ差額を1件登録し、経理が返金したら返金済にする（S-22-002/D-01005/4）
CREATE TABLE REFUND (
    REFUND_NO      CHAR(13)       NOT NULL,
    RESERVE_NO     VARCHAR2(13)   NOT NULL,
    REFUND_AMOUNT  NUMBER(9)      NOT NULL,
    CANCEL_FEE     NUMBER(9)      NOT NULL,
    STATUS         CHAR(1)        DEFAULT '0' NOT NULL,
    CREATED_AT     TIMESTAMP      NOT NULL,
    CREATED_BY     VARCHAR2(10)   NOT NULL,
    UPDATED_AT     TIMESTAMP      NOT NULL,
    UPDATED_BY     VARCHAR2(10)   NOT NULL,
    CONSTRAINT PK_REFUND PRIMARY KEY (REFUND_NO),
    CONSTRAINT FK_REFUND_RESERVE FOREIGN KEY (RESERVE_NO) REFERENCES RESERVE (RESERVE_NO),
    CONSTRAINT CK_REFUND_AMOUNT CHECK (REFUND_AMOUNT >= 0 AND CANCEL_FEE >= 0),
    CONSTRAINT CK_REFUND_STATUS CHECK (STATUS IN ('0', '1'))
);
CREATE INDEX IX_REFUND_RESERVE ON REFUND (RESERVE_NO);
COMMENT ON TABLE  REFUND IS '返金待ち（トランザクション）';
COMMENT ON COLUMN REFUND.REFUND_NO IS '返金番号。F + 取消日の年月日8桁 + その日の連番4桁（S-22-002/D-04012/1）';
COMMENT ON COLUMN REFUND.RESERVE_NO IS '取り消した予約の予約番号';
COMMENT ON COLUMN REFUND.REFUND_AMOUNT IS '返金額（円）。入金額 − 取消料（S-22-002/D-04001/4）';
COMMENT ON COLUMN REFUND.CANCEL_FEE IS '取消料（円）';
COMMENT ON COLUMN REFUND.STATUS IS '返金の状態。値の意味は S-15-001/D-05005/5';
COMMENT ON COLUMN REFUND.CREATED_AT IS '登録日時';
COMMENT ON COLUMN REFUND.CREATED_BY IS '登録した人（会員番号または社員番号）';
COMMENT ON COLUMN REFUND.UPDATED_AT IS '更新日時';
COMMENT ON COLUMN REFUND.UPDATED_BY IS '更新した人（会員番号または社員番号）';
