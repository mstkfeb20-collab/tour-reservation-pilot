-- 振込取込結果。予約の見つからない入金も記録するため、RESERVE への外部キーは張らない（S-20-001/D-05018/3）
CREATE TABLE TRANSFER_IMPORT (
    ACCOUNT_DATE  DATE          NOT NULL,
    INQUIRY_NO    CHAR(6)       NOT NULL,
    AMOUNT        NUMBER(10)    NOT NULL,
    PAYER_NAME    VARCHAR2(48)  NOT NULL,
    RESERVE_NO    VARCHAR2(13),
    RESULT        CHAR(2)       NOT NULL,
    FILE_NAME     VARCHAR2(64)  NOT NULL,
    CONSTRAINT PK_TRANSFER_IMPORT PRIMARY KEY (ACCOUNT_DATE, INQUIRY_NO),
    CONSTRAINT CK_TRANSFER_IMPORT_RESULT CHECK (RESULT IN ('10', '21', '22', '23', '31', '32', '40'))
);
COMMENT ON TABLE  TRANSFER_IMPORT IS '振込入金通知ファイル（IF-11）の明細ごとの取込結果（トランザクション）';
COMMENT ON COLUMN TRANSFER_IMPORT.ACCOUNT_DATE IS '勘定日';
COMMENT ON COLUMN TRANSFER_IMPORT.INQUIRY_NO IS '照会番号。勘定日と合わせて明細を一意に決める';
COMMENT ON COLUMN TRANSFER_IMPORT.AMOUNT IS '振込金額（円）';
COMMENT ON COLUMN TRANSFER_IMPORT.PAYER_NAME IS '振込依頼人名。銀行の明細のまま持つ（S-20-001/D-05019/3）';
COMMENT ON COLUMN TRANSFER_IMPORT.RESERVE_NO IS '振込依頼人名から読み取った予約番号。読み取れなかった明細では NULL';
COMMENT ON COLUMN TRANSFER_IMPORT.RESULT IS '取込結果。値の意味は S-15-001/D-05005/3';
COMMENT ON COLUMN TRANSFER_IMPORT.FILE_NAME IS '取り込んだファイルの名前';
