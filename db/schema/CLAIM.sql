-- 請求待ち。予約を取り消したとき、入金額が取消料より少なければ差額を1件登録し、請求したら請求済にする（S-22-002/D-01005/5）
CREATE TABLE CLAIM (
    CLAIM_NO       CHAR(13)       NOT NULL,
    RESERVE_NO     VARCHAR2(13)   NOT NULL,
    CLAIM_AMOUNT   NUMBER(9)      NOT NULL,
    CANCEL_FEE     NUMBER(9)      NOT NULL,
    PAID_AMOUNT    NUMBER(9)      NOT NULL,
    STATUS         CHAR(1)        DEFAULT '0' NOT NULL,
    CREATED_AT     TIMESTAMP      NOT NULL,
    CREATED_BY     VARCHAR2(10)   NOT NULL,
    UPDATED_AT     TIMESTAMP      NOT NULL,
    UPDATED_BY     VARCHAR2(10)   NOT NULL,
    CONSTRAINT PK_CLAIM PRIMARY KEY (CLAIM_NO),
    CONSTRAINT FK_CLAIM_RESERVE FOREIGN KEY (RESERVE_NO) REFERENCES RESERVE (RESERVE_NO),
    CONSTRAINT CK_CLAIM_AMOUNT CHECK (CLAIM_AMOUNT > 0 AND CANCEL_FEE > 0 AND PAID_AMOUNT >= 0),
    CONSTRAINT CK_CLAIM_STATUS CHECK (STATUS IN ('0', '1'))
);
CREATE INDEX IX_CLAIM_RESERVE ON CLAIM (RESERVE_NO);
COMMENT ON TABLE  CLAIM IS '請求待ち（トランザクション）';
COMMENT ON COLUMN CLAIM.CLAIM_NO IS '請求番号。C + 取消日の年月日8桁 + その日の連番4桁（S-22-002/D-04012/2）';
COMMENT ON COLUMN CLAIM.RESERVE_NO IS '取り消した予約の予約番号';
COMMENT ON COLUMN CLAIM.CLAIM_AMOUNT IS '請求額（円）。取消料 − 入金額（S-22-002/D-04001/5）';
COMMENT ON COLUMN CLAIM.CANCEL_FEE IS '取消料（円）';
COMMENT ON COLUMN CLAIM.PAID_AMOUNT IS '差し引いた入金額（円）。入金がなければ0（S-22-002/D-04001/3）';
COMMENT ON COLUMN CLAIM.STATUS IS '請求の状態。値の意味は S-15-001/D-05005/7';
COMMENT ON COLUMN CLAIM.CREATED_AT IS '登録日時';
COMMENT ON COLUMN CLAIM.CREATED_BY IS '登録した人（会員番号または社員番号）';
COMMENT ON COLUMN CLAIM.UPDATED_AT IS '更新日時';
COMMENT ON COLUMN CLAIM.UPDATED_BY IS '更新した人（会員番号または社員番号）';
