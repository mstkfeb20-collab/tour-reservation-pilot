-- 予約。列・型・制約・説明はこの DDL が正。保持期間・データ量・索引の理由はテーブル設計書 S-16-001 に書く
CREATE TABLE RESERVE (
    RESERVE_NO           VARCHAR2(13)       NOT NULL,
    TOUR_CODE            CHAR(8)            NOT NULL,
    MEMBER_NO            CHAR(10)           NOT NULL,
    ADULT_COUNT          NUMBER(1)          NOT NULL,
    CHILD_COUNT          NUMBER(1)          NOT NULL,
    SUM_PRICE            NUMBER(9)          NOT NULL,
    TRANSFER             CHAR(1)            DEFAULT '0' NOT NULL,
    PAY_DUE_DATE         DATE               NOT NULL,
    REPRESENTATIVE_NAME  NVARCHAR2(20)      NOT NULL,
    REPRESENTATIVE_KANA  NVARCHAR2(40)      NOT NULL,
    BIRTH_DATE           DATE               NOT NULL,
    TEL                  VARCHAR2(11)       NOT NULL,
    MAIL                 VARCHAR2(256)      NOT NULL,
    REMARKS              VARCHAR2(240 BYTE),
    PASSPORT_FILE_ID     VARCHAR2(36),
    REQUEST_TOKEN        VARCHAR2(36)       NOT NULL,
    VERSION              NUMBER(9)          NOT NULL,
    PAID_DATE            DATE,
    PAID_AMOUNT          NUMBER(9),
    LATE_PAYMENT_FLAG    CHAR(1)            DEFAULT '0' NOT NULL,
    CONSTRAINT PK_RESERVE PRIMARY KEY (RESERVE_NO),
    CONSTRAINT UK_RESERVE_TOKEN UNIQUE (REQUEST_TOKEN),
    CONSTRAINT FK_RESERVE_TOUR FOREIGN KEY (TOUR_CODE) REFERENCES TOURINFO (TOUR_CODE),
    CONSTRAINT FK_RESERVE_MEMBER FOREIGN KEY (MEMBER_NO) REFERENCES MEMBER (MEMBER_NO),
    CONSTRAINT CK_RESERVE_COUNT CHECK (ADULT_COUNT >= 0 AND CHILD_COUNT >= 0),
    CONSTRAINT CK_RESERVE_PRICE CHECK (SUM_PRICE >= 0 AND (PAID_AMOUNT IS NULL OR PAID_AMOUNT >= 0)),
    CONSTRAINT CK_RESERVE_TRANSFER CHECK (TRANSFER IN ('0', '1', '9')),
    CONSTRAINT CK_RESERVE_LATE CHECK (LATE_PAYMENT_FLAG IN ('0', '1')),
    CONSTRAINT CK_RESERVE_PAID CHECK ((PAID_DATE IS NULL AND PAID_AMOUNT IS NULL) OR (PAID_DATE IS NOT NULL AND PAID_AMOUNT IS NOT NULL))
);
COMMENT ON TABLE  RESERVE IS 'ツアーの予約（トランザクション）';
COMMENT ON COLUMN RESERVE.RESERVE_NO IS '予約番号';
COMMENT ON COLUMN RESERVE.TOUR_CODE IS '予約したツアーのツアーコード';
COMMENT ON COLUMN RESERVE.MEMBER_NO IS '予約した会員の会員番号';
COMMENT ON COLUMN RESERVE.ADULT_COUNT IS '大人人数';
COMMENT ON COLUMN RESERVE.CHILD_COUNT IS '子供人数';
COMMENT ON COLUMN RESERVE.SUM_PRICE IS '合計金額（円）。予約時の料金で計算して保存する（S-20-001/D-05019/2）';
COMMENT ON COLUMN RESERVE.TRANSFER IS '振込状況。値の意味は S-15-001/D-05005/2';
COMMENT ON COLUMN RESERVE.PAY_DUE_DATE IS '振込期限';
COMMENT ON COLUMN RESERVE.REPRESENTATIVE_NAME IS '代表者の氏名';
COMMENT ON COLUMN RESERVE.REPRESENTATIVE_KANA IS '代表者の氏名（カナ）';
COMMENT ON COLUMN RESERVE.BIRTH_DATE IS '代表者の生年月日';
COMMENT ON COLUMN RESERVE.TEL IS '代表者の電話番号（ハイフンなし）';
COMMENT ON COLUMN RESERVE.MAIL IS '代表者のメールアドレス';
COMMENT ON COLUMN RESERVE.REMARKS IS '備考。80文字 × UTF-8 最大3バイト';
COMMENT ON COLUMN RESERVE.PASSPORT_FILE_ID IS 'パスポートの写しのファイルID。出発日の30日後に削除する';
COMMENT ON COLUMN RESERVE.REQUEST_TOKEN IS '受付トークン。同じ予約の二重登録を防ぐ';
COMMENT ON COLUMN RESERVE.VERSION IS '楽観ロックの版番号。更新のたびに1増やす';
COMMENT ON COLUMN RESERVE.PAID_DATE IS '入金の勘定日。未振込の間は NULL';
COMMENT ON COLUMN RESERVE.PAID_AMOUNT IS '入金額（円）。未振込の間は NULL';
